# -*- coding: utf-8 -*-
"""audit_literals.py: is any word of a test world written into the mind's code?

    python research/living_mind_2026_11_22/audit_literals.py

Reads every module of ``zihin/`` with Python's own parser and collects the string constants of the code that runs
(docstrings are left out: they explain with examples; comments are not in the parse tree at all). Then it takes the
vocabulary of every test world these notes report on (SCAN's command words and action tokens as generated by
``t_scan`` / ``t_scan_splits``, T-dans, T-görev), and prints every place where a word of a test world stands in a
string constant of the code, alone or as one of the words of the string, with the line, so that each can be judged.

A word of a test world that is also an ordinary word of a program ("left", "right", "after", "and", "run" are also
argument values and names in Python and numpy) is printed like any other: the reader sees the line.
Appends the counts to ``results/audit_literals.jsonl``.
"""
from __future__ import annotations

import ast
import json
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(os.path.dirname(HERE))
sys.path.insert(0, ROOT)
sys.path.insert(0, os.path.join(os.path.dirname(HERE), "living_mind_2026_11_15"))
OUT = os.path.join(HERE, "results", "audit_literals.jsonl")


def vocabularies() -> dict:
    import t_dans
    import t_gorev
    import t_scan_splits
    scan = {w for command, answer in t_scan_splits.everything() for w in command + answer}
    dans = {w for command, answer in t_dans.commands() + t_dans.parts() for w in command + answer}
    gorev = {w for command, answer in t_gorev.commands() + t_gorev.parts() for w in command + answer}
    return {"SCAN": scan, "T-dans": dans, "T-görev": gorev}


def docstrings(tree: ast.AST) -> set:
    found = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)) and node.body:
            first = node.body[0]
            if isinstance(first, ast.Expr) and isinstance(first.value, ast.Constant) and isinstance(first.value.value,
                                                                                                    str):
                found.add(id(first.value))
    return found


def main() -> None:
    worlds = vocabularies()
    every = set().union(*worlds.values())
    folder = os.path.join(ROOT, "zihin")
    constants = hits = 0
    lines = ["== words of the test worlds in the string constants of zihin/ (docstrings and comments left out) ==",
             "  vocabularies: " + ", ".join("%s %d words" % (name, len(words)) for name, words in worlds.items())]
    by_word: dict = {}
    for name in sorted(os.listdir(folder)):
        if not name.endswith(".py"):
            continue
        source = open(os.path.join(folder, name), encoding="utf-8").read()
        tree = ast.parse(source)
        skip = docstrings(tree)
        text = source.splitlines()
        for node in ast.walk(tree):
            if not (isinstance(node, ast.Constant) and isinstance(node.value, str)) or id(node) in skip:
                continue
            constants += 1
            words = set(re.findall(r"[^\W\d]+(?:_[^\W\d]+)*", node.value.lower(), flags=re.UNICODE)) | {node.value}
            for word in sorted(words & every):
                hits += 1
                by_word.setdefault(word, []).append("zihin/%s:%d  %s" % (name, node.lineno,
                                                                         text[node.lineno - 1].strip()[:110]))
    lines.append("  string constants read: %d; places where a word of a test world stands: %d" % (constants, hits))
    for word in sorted(by_word):
        lines.append("  %r (%s): %d" % (word, ", ".join(n for n, ws in worlds.items() if word in ws),
                                        len(by_word[word])))
        for place in by_word[word]:
            lines.append("      " + place)
    for line in lines:
        print(line)
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "a", encoding="utf-8") as f:
        f.write(json.dumps({"constants": constants, "hits": hits,
                            "vocabularies": {n: len(w) for n, w in worlds.items()},
                            "by_word": by_word}, ensure_ascii=False) + "\n")


if __name__ == "__main__":
    main()
