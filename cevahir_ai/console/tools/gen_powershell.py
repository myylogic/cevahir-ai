"""Generate the optional PowerShell module ``powershell/Cevahir`` from the command registry.

    python -m cevahir_ai.console.tools.gen_powershell --write    regenerate the two files
    python -m cevahir_ai.console.tools.gen_powershell --check    exit 1 when they are stale

The module is a thin wrapper for real PowerShell 7.2+: one ``Cv``-prefixed function per Cevahir
cmdlet. A function sends one JSON request to ``python -m cevahir_ai -Invoke`` on standard input and
turns the JSON answer into objects, warnings and errors. Parameter values travel as JSON data and
are never spliced into a command line, so there is nothing to quote and nothing to inject.

The files are written with CRLF line endings and are stored in git byte for byte
(``/powershell/** -text``).

The module has not been run on a real PowerShell yet: this environment has no ``pwsh``. What is
tested is that the generated text is in step with the registry and that the ``-Invoke`` protocol
it relies on works.
"""
import sys
from pathlib import Path

from cevahir_ai.console import registry

GUID = "6f1b6c0e-8d0a-4d3b-9c55-0f6f2a7c1e11"
_TYPES = {"string": "[string]", "int": "[int]", "float": "[double]", "bool": "[bool]", "switch": "[switch]",
          "list": "[string[]]", "any": "[object]", "objects": "[object[]]", "path": "[string]",
          "hashtable": "[hashtable]", "scriptblock": "[scriptblock]"}

HEADER = r'''# Cevahir PowerShell module: a thin wrapper over the Python console.
# GENERATED by `python -m cevahir_ai.console.tools.gen_powershell --write`. Do not edit by hand.
# Not yet run on a real PowerShell (see docs/architecture/KONSOL_VE_KAYIT.md, "Sınırlar").

Set-StrictMode -Version 3.0

$script:CvCommonParameters = @(
    'Debug', 'ErrorAction', 'ErrorVariable', 'InformationAction', 'InformationVariable', 'OutBuffer',
    'OutVariable', 'PipelineVariable', 'ProgressAction', 'WarningAction', 'WarningVariable', 'Confirm')
$script:CvCategories = @{
    ObjectNotFound = 'ObjectNotFound'; InvalidArgument = 'InvalidArgument'; InvalidData = 'InvalidData'
    InvalidOperation = 'InvalidOperation'; PermissionDenied = 'PermissionDenied'; SecurityError = 'SecurityError'
    ResourceUnavailable = 'ResourceUnavailable'; OperationStopped = 'OperationStopped'
}

function Get-CvPython {
    <# The interpreter that runs the console: $env:CEVAHIR_PYTHON, else python, python3 or py -3. #>
    if ($env:CEVAHIR_PYTHON) { return , @($env:CEVAHIR_PYTHON) }
    foreach ($name in 'python', 'python3') {
        $found = Get-Command $name -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
        if ($found) { return , @($found.Source) }
    }
    $launcher = Get-Command 'py' -CommandType Application -ErrorAction SilentlyContinue | Select-Object -First 1
    if ($launcher) { return , @($launcher.Source, '-3') }
    throw 'Cevahir: Python was not found. Set $env:CEVAHIR_PYTHON to an interpreter that can import cevahir_ai.'
}

function ConvertTo-CvParameters {
    <# Bound parameters as plain data for the request: common parameters dropped, switches as booleans. #>
    param([Parameter(Mandatory)][System.Collections.IDictionary]$Bound)
    $result = @{}
    foreach ($name in $Bound.Keys) {
        if ($script:CvCommonParameters -contains $name) { continue }
        $value = $Bound[$name]
        if ($value -is [System.Management.Automation.SwitchParameter]) { $value = [bool]$value }
        $result[$name] = $value
    }
    return $result
}

function Invoke-CvPython {
    <# Run the console with $Arguments, $Text on its standard input, UTF-8 both ways. Returns stdout. #>
    param([Parameter(Mandatory)][string[]]$Arguments, [Parameter(Mandatory)][AllowEmptyString()][string]$Text)
    $python = Get-CvPython
    $prefix = @()
    if ($python.Count -gt 1) { $prefix = $python[1..($python.Count - 1)] }
    $root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
    $saved = @{ Console = [Console]::OutputEncoding; Pipe = $OutputEncoding; Path = $env:PYTHONPATH; Utf8 = $env:PYTHONUTF8 }
    try {
        [Console]::OutputEncoding = [System.Text.UTF8Encoding]::new($false)
        $OutputEncoding = [System.Text.UTF8Encoding]::new($false)
        $env:PYTHONUTF8 = '1'
        if (Test-Path (Join-Path $root 'cevahir_ai')) {
            $env:PYTHONPATH = if ($saved.Path) { $root + [IO.Path]::PathSeparator + $saved.Path } else { $root }
        }
        $output = $Text | & $python[0] @prefix '-m' 'cevahir_ai' @Arguments
        $global:LASTEXITCODE = $LASTEXITCODE
        return ($output -join "`n")
    }
    finally {
        [Console]::OutputEncoding = $saved.Console
        $OutputEncoding = $saved.Pipe
        $env:PYTHONPATH = $saved.Path
        $env:PYTHONUTF8 = $saved.Utf8
    }
}

function ConvertFrom-CvRecord {
    <# A JSON record as a PowerShell object whose type name is the record's __type. #>
    param($Record)
    if ($Record -is [System.Management.Automation.PSCustomObject] -and $Record.PSObject.Properties['__type']) {
        $Record.PSTypeNames.Insert(0, [string]$Record.__type)
        $Record.PSObject.Properties.Remove('__type')
    }
    return $Record
}

function Invoke-CvHost {
    <# One cmdlet call: send {command, parameters, input} as JSON, emit records, warnings and errors. #>
    [CmdletBinding()]
    param(
        [Parameter(Mandatory)][string]$Command,
        [System.Collections.IDictionary]$Parameters = @{},
        [object[]]$InputObject = @()
    )
    $request = @{ command = $Command; parameters = $Parameters; input = $InputObject } | ConvertTo-Json -Depth 32 -Compress
    $raw = Invoke-CvPython -Arguments @('-Invoke') -Text $request
    if (-not $raw) { throw "Cevahir: the console returned nothing for $Command (exit code $LASTEXITCODE)." }
    $result = $raw | ConvertFrom-Json -Depth 64
    foreach ($message in @($result.warnings)) { Write-Warning $message }
    foreach ($record in @($result.records)) { ConvertFrom-CvRecord $record }
    foreach ($failure in @($result.errors)) {
        $category = $script:CvCategories[[string]$failure.category]
        if (-not $category) { $category = 'NotSpecified' }
        Write-Error -Message $failure.message -ErrorId $failure.fully_qualified_error_id -Category $category
    }
    $global:LASTEXITCODE = [int]$result.exit
}

function Invoke-Cevahir {
    <#
    .SYNOPSIS
    Runs a script of the console language (its own Where-Object, Format-Table ...) and returns its objects.
    .EXAMPLE
    Invoke-Cevahir 'Get-Checkpoint | Sort-Object Epoch -Descending | Select-Object -First 3'
    #>
    [CmdletBinding()]
    param([Parameter(Mandatory, Position = 0)][string]$Script)
    $raw = Invoke-CvPython -Arguments @('-OutputFormat', 'Json') -Text $Script
    if ($raw) { foreach ($record in @($raw | ConvertFrom-Json -Depth 64)) { ConvertFrom-CvRecord $record } }
}
'''


def cv_name(command):
    verb, _, noun = command.name.partition("-")
    return f"{verb}-Cv{noun}"


def module_commands():
    return [command for command in registry.commands() if command.module]


def _parameter(command, parameter):
    from cevahir_ai.console.help import pick
    options = []
    if parameter.mandatory:
        options.append("Mandatory")
    if parameter.position is not None:
        options.append(f"Position = {parameter.position}")
    if parameter.pipeline in ("value", "both"):
        options.append("ValueFromPipeline")
    if parameter.pipeline in ("property", "both"):
        options.append("ValueFromPipelineByPropertyName")
    text = f"[Parameter({', '.join(options)})]"
    if parameter.aliases:
        text += "[Alias(" + ", ".join(f"'{alias}'" for alias in parameter.aliases) + ")]"
    if parameter.choices:
        text += "[ValidateSet(" + ", ".join(f"'{choice}'" for choice in parameter.choices) + ")]"
    description = pick(parameter.help, "en").replace("\n", " ")
    return f"        # {description}\n        {text}{_TYPES[parameter.type]}${parameter.name}"


def function_text(command):
    from cevahir_ai.console.help import pick
    parameters = [_parameter(command, parameter) for parameter in command.params]
    if command.whatif:
        parameters.append("        # Show what would happen; change nothing.\n        [Parameter()][switch]$WhatIf")
    lines = [f"function {cv_name(command)} {{", "    <#", "    .SYNOPSIS", f"    {pick(command.synopsis, 'en')}"]
    for code, english, _ in command.examples[:2]:
        for other in module_commands():                      # every Cevahir cmdlet in the example gets its Cv name
            code = code.replace(other.name, cv_name(other))
        lines += ["    .EXAMPLE", "    " + code]
    lines += ["    #>", "    [CmdletBinding()]"]
    if command.output:
        lines.append(f"    [OutputType('{command.output}')]")
    lines += ["    param(", ",\n".join(parameters), "    )"]
    if command.kind == "stream":
        collected = next(parameter.name for parameter in command.params if parameter.type == "list")
        lines += ["    begin { $collected = @() }",
                  "    process {",
                  f"        if ($_ -and $_.PSObject.Properties['{collected}']) {{ $collected += [string]$_.{collected} }}",
                  "    }",
                  "    end {",
                  "        $bound = ConvertTo-CvParameters $PSBoundParameters",
                  f"        if ($collected.Count) {{ $bound['{collected}'] = @(@($bound['{collected}']) + $collected | Where-Object {{ $_ }}) }}",
                  f"        Invoke-CvHost -Command '{command.name}' -Parameters $bound",
                  "    }"]
    else:
        lines += [f"    process {{ Invoke-CvHost -Command '{command.name}' -Parameters (ConvertTo-CvParameters $PSBoundParameters) }}"]
    lines.append("}")
    return "\n".join(lines)


def psm1():
    names = [cv_name(command) for command in module_commands()]
    body = [HEADER.rstrip("\n"), "", "# ---- generated functions: one per Cevahir cmdlet " + "-" * 40, ""]
    for command in module_commands():
        body += [function_text(command), ""]
    exported = ", ".join(f"'{name}'" for name in names + ["Invoke-Cevahir"])
    body += [f"Export-ModuleMember -Function @({exported})", ""]
    return "\n".join(body)


def psd1():
    from cevahir_ai import __version__
    names = [cv_name(command) for command in module_commands()] + ["Invoke-Cevahir"]
    functions = ",\n".join(f"        '{name}'" for name in names)
    return f"""# GENERATED by `python -m cevahir_ai.console.tools.gen_powershell --write`. Do not edit by hand.
@{{
    RootModule           = 'Cevahir.psm1'
    ModuleVersion        = '{__version__}'
    GUID                 = '{GUID}'
    Author               = 'Cevahir AI'
    Description          = 'Cv-prefixed wrappers over the Cevahir Python console (python -m cevahir_ai). PowerShell 7.2 or later.'
    PowerShellVersion    = '7.2'
    CompatiblePSEditions = @('Core')
    FunctionsToExport    = @(
{functions}
    )
    CmdletsToExport      = @()
    VariablesToExport    = @()
    AliasesToExport      = @()
}}
"""


def files():
    """``{file name: bytes}`` of the module, with CRLF line endings."""
    return {name: text.replace("\r\n", "\n").replace("\n", "\r\n").encode("utf-8")
            for name, text in (("Cevahir.psd1", psd1()), ("Cevahir.psm1", psm1()))}


def module_directory(root=None):
    from cevahir_ai._compat.repo import repo_root
    return Path(root or repo_root()) / "powershell" / "Cevahir"


def stale(root=None):
    directory = module_directory(root)
    return [name for name, data in files().items()
            if not (directory / name).is_file() or (directory / name).read_bytes() != data]


def main(argv=None):
    argv = list(sys.argv[1:] if argv is None else argv)
    if argv == ["--write"]:
        directory = module_directory()
        directory.mkdir(parents=True, exist_ok=True)
        for name, data in files().items():
            (directory / name).write_bytes(data)
            print(f"wrote {directory / name}")
        return 0
    if argv == ["--check"]:
        names = stale()
        for name in names:
            print(f"stale: powershell/Cevahir/{name} (run gen_powershell --write)", file=sys.stderr)
        return 1 if names else 0
    print(__doc__.split("\n\n")[1], file=sys.stderr)
    return 2


if __name__ == "__main__":
    sys.exit(main())
